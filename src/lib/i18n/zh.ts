const dayLabel = (date: string) => {
  const d = new Date(`${date}T12:00:00`);
  return d.toLocaleDateString("zh-CN", d.getFullYear() === new Date().getFullYear()
    ? { month: "short", day: "numeric" } : { year: "numeric", month: "short", day: "numeric" });
};

