/**
 * ---- 8. AI workspace, admin only ------------------------------------------
 *
 * Seven new tables for the admin-only AI Workspace: projects, conversations,
 * messages with explicit reply lineage, files with tombstones, the files each
 * message carries, per-provider copies of files, and per-admin settings such as
 * the versioned upload disclosure.
 *
 * Additive only. Nothing that exists is read, altered or dropped, and no row
 * outside these tables is touched. Every statement is guarded, so a second run
 * reports no changes. db/schema.sql carries the same definitions for fresh
 * installs; tests/ai-workspace-migration.test.ts proves both produce the same
 * structure.
 *
 * Its own module so the tests run exactly this code, the pattern step 4e uses.
 * `client` is anything with `query(sql, params) → { rows }`.
 */

/** In creation order: each table only references tables before it. */
export const AI_WORKSPACE_STEPS = [
  {
    table: "ai_projects",
    statements: [
    `create table if not exists ai_projects (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references users on delete cascade,
  name          text not null check (length(btrim(name)) between 1 and 120),
  -- Private. The project context layer for this project's conversations only.
  instructions  text not null default '' check (length(instructions) <= 20000),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  archived_at   timestamptz,
  unique (id, user_id)
)`,
    `create index if not exists ai_projects_owner_idx
  on ai_projects (user_id, updated_at desc) where archived_at is null`,
    ],
  },
  {
    table: "ai_conversations",
    statements: [
    `create table if not exists ai_conversations (
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid not null references users on delete cascade,
  -- Null for a standalone chat.
  project_id       uuid,
  title            text not null default '' check (length(title) <= 200),
  title_edited     boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  last_message_at  timestamptz not null default now(),
  archived_at      timestamptz,
  unique (id, user_id),
  foreign key (project_id, user_id) references ai_projects (id, user_id) on delete cascade
)`,
    `create index if not exists ai_conversations_recent_idx
  on ai_conversations (user_id, last_message_at desc) where archived_at is null`,
    `create index if not exists ai_conversations_project_idx
  on ai_conversations (project_id, last_message_at desc) where project_id is not null`,
    ],
  },
  {
    table: "ai_messages",
    statements: [
    `create table if not exists ai_messages (
  id                          uuid primary key default gen_random_uuid(),
  conversation_id             uuid not null,
  user_id                     uuid not null,
  role                        text not null check (role in ('user', 'assistant')),
  content                     text not null default '' check (length(content) <= 500000),
  status                      text not null default 'complete'
                              check (status in ('streaming', 'complete', 'stopped', 'failed')),
  error_code                  text check (error_code in ('rate_limited', 'overloaded', 'timeout',
                                'context_too_long', 'unreadable_file', 'malformed_response',
                                'provider_error', 'network', 'interrupted')),
  -- Idempotent sends: generated by the browser, unique per admin.
  client_id                   uuid,
  -- Lineage, explicit and never inferred from text or order.
  --   reply         answers reply_to_message_id
  --   continuation  carries on from continuation_of_message_id
  --   retry         replaces retry_of_message_id
  reply_kind                  text check (reply_kind in ('reply', 'continuation', 'retry')),
  reply_to_message_id         uuid,
  continuation_of_message_id  uuid,
  retry_of_message_id         uuid,
  -- Metadata only, and provider-neutral.
  provider                    text check (provider ~ '^[a-z0-9_-]{1,40}$'),
  model                       text check (length(model) <= 80),
  max_output_tokens           integer check (max_output_tokens between 1 and 128000),
  stop_reason                 text check (length(stop_reason) <= 40),
  input_tokens                integer check (input_tokens >= 0),
  output_tokens               integer check (output_tokens >= 0),
  cache_read_tokens           integer check (cache_read_tokens >= 0),
  cache_write_tokens          integer check (cache_write_tokens >= 0),
  context_messages            integer check (context_messages >= 0),
  latency_ms                  integer check (latency_ms >= 0),
  created_at                  timestamptz not null default now(),
  completed_at                timestamptz,
  -- Targets for composite keys: lineage stays in one conversation, attachments with one owner.
  unique (id, conversation_id),
  unique (id, user_id),
  foreign key (conversation_id, user_id)
    references ai_conversations (id, user_id) on delete cascade,
  foreign key (reply_to_message_id, conversation_id)
    references ai_messages (id, conversation_id) on delete cascade,
  foreign key (continuation_of_message_id, conversation_id)
    references ai_messages (id, conversation_id) on delete cascade,
  foreign key (retry_of_message_id, conversation_id)
    references ai_messages (id, conversation_id) on delete cascade,
  -- A user message is always complete and carries no lineage or provider metadata.
  -- An assistant message always answers a user message and has exactly one kind.
  check (
    (role = 'user'
      and status = 'complete' and provider is null and reply_kind is null
      and reply_to_message_id is null
      and continuation_of_message_id is null and retry_of_message_id is null)
    or
    (role = 'assistant' and reply_to_message_id is not null and (
         (reply_kind = 'reply'
            and continuation_of_message_id is null and retry_of_message_id is null)
      or (reply_kind = 'continuation'
            and continuation_of_message_id is not null and retry_of_message_id is null)
      or (reply_kind = 'retry'
            and retry_of_message_id is not null and continuation_of_message_id is null)))
  ),
  check (reply_to_message_id is distinct from id
     and continuation_of_message_id is distinct from id
     and retry_of_message_id is distinct from id)
)`,
    `create index if not exists ai_messages_conversation_idx
  on ai_messages (conversation_id, created_at)`,
    `create index if not exists ai_messages_reply_to_idx
  on ai_messages (reply_to_message_id) where reply_to_message_id is not null`,
    `create index if not exists ai_messages_usage_idx
  on ai_messages (user_id, created_at) where role = 'assistant'`,
    `create unique index if not exists ai_messages_client_idx
  on ai_messages (user_id, client_id) where client_id is not null`,
    `create unique index if not exists ai_messages_continued_once_idx
  on ai_messages (continuation_of_message_id) where continuation_of_message_id is not null`,
    `create unique index if not exists ai_messages_retried_once_idx
  on ai_messages (retry_of_message_id) where retry_of_message_id is not null`,
    ],
  },
  {
    table: "ai_files",
    statements: [
    `create table if not exists ai_files (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null references users on delete cascade,
  project_id         uuid,
  conversation_id    uuid,
  -- As uploaded, after removing control characters and path separators.
  original_filename  text not null check (length(original_filename) between 1 and 255),
  kind               text not null check (kind in ('pdf', 'image', 'text')),
  -- Decided by the server from the bytes, never taken from the browser.
  mime_type          text not null check (mime_type in ('application/pdf', 'image/png',
                       'image/jpeg', 'image/gif', 'image/webp', 'text/plain')),
  -- A backstop only; the real per-kind limits and the quota are configuration.
  byte_size          integer not null check (byte_size between 1 and 33554432),
  sha256             text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  -- Cleared on deletion. The row stays as a tombstone so history can say "File removed".
  content            bytea,
  created_at         timestamptz not null default now(),
  deleted_at         timestamptz,
  check ((deleted_at is null) = (content is not null)),
  check (content is null or octet_length(content) = byte_size),
  check (num_nonnulls(project_id, conversation_id) = 1),
  unique (id, user_id),
  foreign key (project_id, user_id) references ai_projects (id, user_id) on delete cascade,
  foreign key (conversation_id, user_id) references ai_conversations (id, user_id) on delete cascade
)`,
    `create index if not exists ai_files_project_idx
  on ai_files (project_id, created_at desc) where project_id is not null and deleted_at is null`,
    `create index if not exists ai_files_conversation_idx
  on ai_files (conversation_id, created_at) where conversation_id is not null and deleted_at is null`,
    `create index if not exists ai_files_quota_idx
  on ai_files (user_id) include (byte_size) where deleted_at is null`,
    `create unique index if not exists ai_files_dedupe_idx
  on ai_files (user_id, coalesce(project_id, conversation_id), sha256) where deleted_at is null`,
    ],
  },
  {
    table: "ai_message_files",
    statements: [
    `create table if not exists ai_message_files (
  message_id  uuid not null,
  file_id     uuid not null,
  user_id     uuid not null,
  -- Order shown and sent. 20 per message is a data-layer rule; this is a backstop.
  position    smallint not null check (position between 0 and 99),
  created_at  timestamptz not null default now(),
  primary key (message_id, file_id),
  unique (message_id, position),
  -- Both keys include user_id, so a message can never carry another admin's file.
  foreign key (message_id, user_id) references ai_messages (id, user_id) on delete cascade,
  -- No cascade, checked at commit: a file with attachment history is tombstoned rather than
  -- removed, and can only disappear in the transaction that removes every message using it.
  foreign key (file_id, user_id) references ai_files (id, user_id)
    deferrable initially deferred
)`,
    `create index if not exists ai_message_files_file_idx
  on ai_message_files (file_id)`,
    ],
  },
  {
    table: "ai_file_provider_copies",
    statements: [
    `create table if not exists ai_file_provider_copies (
  file_id           uuid not null references ai_files on delete cascade,
  provider          text not null check (provider ~ '^[a-z0-9_-]{1,40}$'),
  -- Server-side only. Never sent to a browser or accepted from one.
  provider_file_id  text check (length(provider_file_id) <= 200),
  status            text not null default 'pending'
                    check (status in ('pending', 'uploaded', 'failed', 'deleted')),
  uploaded_at       timestamptz,
  deleted_at        timestamptz,
  failure_code      text check (length(failure_code) <= 40),
  updated_at        timestamptz not null default now(),
  primary key (file_id, provider),
  check (status <> 'uploaded' or (provider_file_id is not null and uploaded_at is not null)),
  check (status <> 'deleted' or deleted_at is not null)
)`,
    ],
  },
  {
    table: "ai_workspace_settings",
    statements: [
    `create table if not exists ai_workspace_settings (
  user_id                        uuid primary key references users on delete cascade,
  -- Versioned acceptance of the upload disclosure; never a boolean.
  upload_disclosure_version      integer check (upload_disclosure_version >= 1),
  upload_disclosure_accepted_at  timestamptz,
  created_at                     timestamptz not null default now(),
  updated_at                     timestamptz not null default now(),
  check ((upload_disclosure_version is null) = (upload_disclosure_accepted_at is null))
)`,
    ],
  },
];

export const AI_WORKSPACE_TABLES = AI_WORKSPACE_STEPS.map((step) => step.table);

async function tableExists(client, table) {
  const { rows } = await client.query(
    `select 1 from information_schema.tables
      where table_schema = 'public' and table_name = $1`,
    [table],
  );
  return rows.length > 0;
}

export async function migrateAiWorkspace(client, log = () => {}) {
  // Every table here belongs to a user. Absent only on a database that has not
  // reached the base schema, where there is nothing to attach to yet.
  if (!(await tableExists(client, "users"))) return 0;

  let changed = 0;
  for (const { table, statements } of AI_WORKSPACE_STEPS) {
    const existed = await tableExists(client, table);
    // `if not exists` on every statement: an index missing from an existing
    // table is still created, and nothing present is replaced.
    for (const statement of statements) await client.query(statement);
    if (!existed) {
      log(`  created ${table}`);
      changed++;
    }
  }
  return changed;
}
